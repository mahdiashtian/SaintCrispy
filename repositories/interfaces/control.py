"""Ports for operational services; adapters own SQL and Redis."""

from typing import Protocol

from schemas.membership import HumanProfile, MembershipEvent


class MembershipRepository(Protocol):
    async def apply(self, event: MembershipEvent) -> bool: ...
    async def known_active(self, chat_id: int, user_id: int) -> bool: ...
    async def known_member(self, chat_id: int, user_id: int) -> bool: ...
    async def departure(self, chat_id, user_id, occurred_at, event_key) -> None: ...
    async def refresh_profile(
        self, user_id, username, first_name, last_name, *, deleted=False, bot=False
    ) -> None: ...
    async def profile(
        self,
        user_id: int,
        username: str | None,
        first_name: str | None,
        last_name: str | None,
        *,
        occurred_at=None,
    ) -> None: ...


class ControlRepository(Protocol):
    async def authorized(self, user_id: int) -> bool: ...
    async def setting(self, key: str, default=None): ...
    async def stats(self) -> dict: ...
    async def banned(self, user_id: int) -> bool: ...


class ObjectCache(Protocol):
    async def read(self, kind: str, identity: int | str, loader): ...
    async def put(self, kind: str, identity: int | str, value): ...
    async def invalidate(self, kind: str, identity: int | str): ...


class ActivityStream(Protocol):
    shards: int

    async def append(self, event: MembershipEvent | HumanProfile): ...
    async def batch(self, shard: int, consumer: str): ...
    async def acknowledge(self, shard: int, ids: list[str]): ...
    async def quarantine(self, shard: int, identity: str): ...
    def shard(self, chat_id: int) -> int: ...
