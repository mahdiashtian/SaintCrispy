def promo(group, seed):
    # Promos and administrator reminders have separate pools, as in Couplyo.
    # Stable selection keeps retries on the same variant and Telegram random_id.
    line = GROUP_PROMO[seed % len(GROUP_PROMO)]
    if (seed // len(GROUP_PROMO)) % 100 < 35:
        line += "\n" + PROMO_HELP_HINTS[(seed // 100) % len(PROMO_HELP_HINTS)]
    return line


def need_admin(group, seed):
    owner = group.owner_id
    admins = f'<a href="tg://user?id={owner}">مالک گروه</a>' if owner else "ادمین‌های گروه"
    return GROUP_NEED_ADMIN[seed % len(GROUP_NEED_ADMIN)].format(admins=admins)


def removed_nudge(group, recipient, seed, *, with_name=True):
    name = html.escape(group.title or str(group.chat_id)) if with_name else "گروهی که مدیریت می‌کنی"
    pool = OWNER_NUDGE if recipient == group.owner_id else GROUP_ADMIN_NUDGE
    return pool[seed % len(pool)].format(group=name)
