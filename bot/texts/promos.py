def promo(group, seed):
    if group.is_admin is True:
        return (
            GROUP_PROMO[seed % len(GROUP_PROMO)] + "\n\nلینک رسانه را همین‌جا بفرست. راهنما: /start"
        )
    owner = group.owner_id
    admins = f'<a href="tg://user?id={owner}">مالک گروه</a>' if owner else "ادمین‌های گروه"
    variants = [
        "{admins} ادمینم کنید لطفاً.",
        "سلام {admins} 👋 یه تیکِ ادمین می‌خوام، همین.",
        "{admins} هر وقت راحت بودید ادمینم کنید. عجله‌ای نیست.",
    ]
    return variants[seed % len(variants)].format(admins=admins) + "\nبرای خواندن فهرست اعضای گروه."
